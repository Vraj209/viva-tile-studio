function normalizeSearch(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[’']/g, "")
    .replace(/\./g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

const searchIndex = countries.map((country) => ({
  country,
  names: [country.name, ...(aliases[country.code] ?? [])].map(normalizeSearch),
}));

/**
 * Search fixed English names, alpha-2/alpha-3 codes, and aliases without accents
 * or case sensitivity. An exact code/short alias wins over incidental substring
 * matches (for example, "US" returns United States, not Australia or Austria).
 * Otherwise every query word must occur in one name/alias, in any order.
 * Display-name matches precede alias-only matches; each group stays alphabetical.
 * Callers receive a fresh array.
 */
export function filterCountries(query: string): Country[] {
  if (!query.trim()) return [...countries];

  const normalized = normalizeSearch(query);
  if (!normalized) return [];

  const exact = searchIndex.filter(
    ({ country, names }) =>
      country.code.toLowerCase() === normalized ||
      (normalized.length <= 3 && names.includes(normalized)),
  );
  if (exact.length) return exact.map(({ country }) => country);

  const words = normalized.split(/\s+/);
  const matches = (name: string) => words.every((word) => name.includes(word));
  const direct: Country[] = [];
  const alternate: Country[] = [];
  for (const { country, names } of searchIndex) {
    if (matches(names[0])) direct.push(country);
    else if (names.slice(1).some(matches)) alternate.push(country);
  }
  return [...direct, ...alternate];
}
